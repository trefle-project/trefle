#!/usr/bin/env bash
# 017-edge-protection (research R4, R5) — Cloudflare's published address
# ranges, in the two places that need them:
#   - infra/deploy/cloudflare-ips.caddy: the `trusted_proxies` directive the
#     Caddyfile imports, so Caddy trusts CF-Connecting-IP only from Cloudflare;
#   - printed below: the list origin-firewall.sh puts in the Hostinger VPS
#     firewall (443/tcp).
#
# Usage: infra/cloudflare/refresh-ips.sh
# Then commit the snippet and deploy (release.sh reloads Caddy), and update
# the firewall (origin-firewall.sh) if the printed list changed. Ranges change a few times a year.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
out="$(cd "$here/../deploy" && pwd)/cloudflare-ips.caddy"

fetch() {
  curl -fsS --retry 3 "$1" | tr -d '\r' | grep -E '^[0-9a-fA-F:.]+/[0-9]+$'
}
v4="$(fetch https://www.cloudflare.com/ips-v4)"
v6="$(fetch https://www.cloudflare.com/ips-v6)"
[[ -n "$v4" && -n "$v6" ]] || { echo "refresh-ips: empty list from cloudflare.com, nothing written" >&2; exit 1; }
ranges="$(printf '%s\n%s\n' "$v4" "$v6")"

{
  echo "# Generated by infra/cloudflare/refresh-ips.sh — do not edit by hand."
  echo "# Source: https://www.cloudflare.com/ips-v4 and ips-v6"
  echo "# Imported inside the Caddyfile's global \`servers { }\` block."
  printf 'trusted_proxies static %s\n' "$(tr '\n' ' ' <<<"$ranges" | sed 's/ $//')"
} >"$out"

echo "Wrote $out ($(wc -l <<<"$ranges" | tr -d ' ') ranges)."
echo
echo "Hostinger firewall (infra/cloudflare/origin-firewall.sh applies it) — 443/tcp from each of these:"
echo "$ranges"
