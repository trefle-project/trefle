#!/usr/bin/env bash
# Local dev / CI only: write infra/.env from infra/.env.example with freshly
# generated secrets. Never use the result in production — follow
# infra/deploy/README.md there (preflight.sh checks every value).
#
#   infra/dev-env.sh           refuses to overwrite an existing infra/.env
#   infra/dev-env.sh --force   overwrites it
set -euo pipefail
cd "$(dirname "$0")"
[ -e .env ] && [ "${1:-}" != "--force" ] && { echo "infra/.env already exists (use --force to overwrite)" >&2; exit 1; }

hex() { openssl rand -hex "$1"; }
cp .env.example .env
{
  echo
  echo "# ---- generated by infra/dev-env.sh for local dev ----"
  echo "PAYLOAD_SECRET=$(hex 32)"
  echo "CMS_SERVICE_API_KEY=$(hex 16)"
  echo "REVALIDATE_SECRET=$(hex 32)"
  echo "UNSUBSCRIBE_SECRET=$(hex 32)"
  echo "CONFIRM_TOKEN_SECRET=$(hex 32)"
  echo "FORM_TOKEN_SECRET=$(hex 32)"
  echo "IMGPROXY_KEY=$(hex 32)"
  echo "IMGPROXY_SALT=$(hex 32)"
  echo "GROWTHBOOK_JWT_SECRET=$(hex 32)"
  echo "GROWTHBOOK_ENCRYPTION_KEY=$(hex 32)"
  echo "GROWTHBOOK_PG_PASSWORD=$(hex 24)"
  # The e2e specs default to this value (infra/docker-compose.e2e.yml).
  echo "EDGE_SYNC_SECRET=dev-edge-sync-secret-not-for-production-0000"
} >> .env
echo "wrote infra/.env"
