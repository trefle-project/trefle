/**
 * The published-page HTML allow-list (003-post-launch-improvements, FR-003).
 * The renderer's sanitiser (apps/web/src/lib/render.ts) applies it; it lives
 * here since 012-url-page-import so the import serializer's tests can assert
 * it only ever emits markup that survives publishing (FR-008), against the
 * very same list.
 *
 * 014-custom-code-editing (FR-011/FR-015) widened it: editors can now write
 * the page's HTML directly in the editor's « Code » view, so the list covers
 * what hand-written landing-page markup needs (tables, buttons, media,
 * iframes, inline SVG, sectioning elements). `SANITIZE_CONFIG` below is the
 * one DOMPurify config used by publication, by the « Code » view's
 * "what will be dropped" warning and by the import tests — the three can't
 * disagree.
 *
 * Still never allowed, whoever wrote the markup: `<script>`, `<style>`,
 * `on…` event attributes, `javascript:`/non-image `data:` URIs, `<form>` and
 * its inputs (every lead goes through the platform's own form),
 * `<object>`/`<embed>`, `iframe[srcdoc]`, `name` (DOM clobbering). Running
 * code only ever comes from the admin-only page scripts and code blocks,
 * which never pass through this list.
 *
 * DOMPurify matches tag and attribute names lower-cased in HTML documents,
 * hence `lineargradient`, `viewbox` etc. below.
 */
